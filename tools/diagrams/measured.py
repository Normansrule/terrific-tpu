def synth_chart():
    path = os.path.join(ROOT, "data", "synth.csv")
    rows = [r for r in csv.DictReader(open(path)) if r["area_um2"]]
    if not rows:
        print("  (no sky130 area data; run make synth with the PDK installed)")
        return
    s = Svg(980, 520, "How big is it? Systolic array area in SkyWater 130 nm",
            ["Synthesized with Yosys onto sky130_fd_sc_hd standard cells (tools/synth_report.sh, data/synth.csv).",
             "Area grows with N² because the PE count does. v2's shadow registers cost about 8 % more area."])
    arr = [r for r in rows if r["design"].startswith("systolic")]
    Ns = sorted({int(r["N"]) for r in arr})
    mx = max(float(r["area_um2"]) for r in arr)
    x0, y0, y1 = 140, 450, 130
    for i, n in enumerate(Ns):
        for j, ver in enumerate(("v1_simple", "v2_pipelined")):
            r = next(r for r in arr if int(r["N"]) == n and r["version"] == ver)
            a = float(r["area_um2"])
            h = a / mx * (y0 - y1)
            x = x0 + i * 250 + j * 80
            col = C["wt"] if j == 0 else C["mxu"]
            s.rect(x, y0 - h, 70, h, col, None, 0, 4, opacity=0.9)
            s.text(x + 35, y0 - h - 26, f"{a / 1e6:.3f} mm²", 12, col, 700, "middle")
            s.text(x + 35, y0 - h - 10, f"{int(r['cells']):,} cells", 11, C["muted"], anchor="middle")
        s.text(x0 + i * 250 + 75, y0 + 24, f"N = {n}  ({n * n} PEs)", 14, C["ink"], 700, "middle")
    pe = next((r for r in rows if r["design"] == "pe"), None)
    if pe:
        a = float(pe["area_um2"])
        tx = 140
        s.text(tx, 180, f"one PE ≈ {a:,.0f} µm²", 15, C["ink"], 700)
        s.text(tx, 204, f"x 65,536 PEs (TPU v1 size)", 13, C["muted"])
        s.text(tx, 224, f"≈ {a * 65536 / 1e6:,.0f} mm² at 130 nm", 13, C["red"], 700)
        s.text(tx, 248, "TPU v1's whole die, at 28 nm, was", 13, C["muted"])
        s.text(tx, 268, "under 331 mm². Smaller transistors", 13, C["muted"])
        s.text(tx, 288, "are the other half of the story.", 13, C["muted"])
    s.legend(400, 150, [(C["wt"], "v1_simple"), (C["mxu"], "v2_pipelined")], 160)
    s.save(P("synth_area.svg"))


ALL = [waveform, gantt, utilization, synth_chart]
